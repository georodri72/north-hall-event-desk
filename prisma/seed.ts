async function main() {
  const force = process.argv.includes("--force");
  const existing = await prisma.user.count();
  if (existing > 0 && !force) {
    console.log("North Hall already has data. Skipping seed. Run npm run db:reset to rebuild the sample week.");
    return;
  }

  const today = venueToday();
  const passwordHash = await bcrypt.hash("harbor-demo", 10);
  await prisma.user.upsert({
    where: { email: "sv@northhall.example" },
    update: { name: "SV", title: "Production Coordinator", passwordHash },
    create: {
      id: "user_sv",
      email: "sv@northhall.example",
      name: "SV",
      title: "Production Coordinator",
      passwordHash,
    },
  });

  for (const room of rooms) {
    const data = {
      name: room.name,
      floor: room.floor,
      summary: room.summary,
      builtInAv: room.builtInAv,
      capacities: JSON.stringify(room.capacities),
      sortOrder: room.sortOrder,
    };
    await prisma.room.upsert({ where: { id: room.id }, update: data, create: { id: room.id, ...data } });
  }

  const holds: HoldWindow[] = bookingSeeds.map((booking) => ({
    id: booking.id,
    eventName: booking.eventName,
    date: addDays(today, booking.day),
    roomId: booking.roomId,
    startMin: minutes(booking.start),
    endMin: minutes(booking.end),
    setupMin: booking.setup ?? 30,
    teardownMin: booking.teardown ?? 30,
    status: booking.status ?? "confirmed",
  }));

  for (const hold of holds) {
    const hits = findConflicts(hold, holds);
    if (hits.length) {
      throw new Error(`Seed overlap: ${hold.eventName} conflicts with ${hits.map((hit) => hit.eventName).join(", ")}`);
    }
  }

  for (const booking of bookingSeeds) {
    const data = {
      eventName: booking.eventName,
      organization: booking.organization,
      requesterName: booking.requesterName,
      requesterEmail: booking.requesterEmail,
      requesterPhone: booking.requesterPhone,
      onsiteName: booking.onsiteName ?? "",
      onsitePhone: booking.onsitePhone ?? "",
      onsiteEmail: booking.onsiteEmail ?? "",
      date: addDays(today, booking.day),
      startMin: minutes(booking.start),
      endMin: minutes(booking.end),
      setupMin: booking.setup ?? 30,
      teardownMin: booking.teardown ?? 30,
      roomId: booking.roomId,
      headcount: booking.headcount,
      setupStyle: booking.setupStyle,
      status: booking.status ?? "confirmed",
      avItems: JSON.stringify((booking.av ?? []).map((item) => ({ id: item.id, qty: item.qty ?? 1 }))),
      avNotes: booking.avNotes ?? "",
      cateringItems: JSON.stringify(
        (booking.catering ?? []).map((meal, index) => ({
          id: `${booking.id}-meal-${index + 1}`,
          meal: meal.meal,
          time: meal.time,
          count: meal.count,
          notes: meal.notes ?? "",
        })),
      ),
      notes: booking.notes ?? "",
      timeline: "[]",
      narrative: "",
      draftSource: "",
    };
    await prisma.booking.upsert({
      where: { id: booking.id },
      update: data,
      create: { id: booking.id, ...data },
    });
  }

  console.log(`Seeded North Hall around ${today}. Sign in as sv@northhall.example / harbor-demo`);
}

main()
  .catch((error) => {
    console.error(error);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
